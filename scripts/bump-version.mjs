import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const version = process.argv[2];
if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) throw new Error('Usage: npm run release:bump -- <major.minor.patch>');
const root = fileURLToPath(new URL('../', import.meta.url));
const previous = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8')).version;
const manifests = ['package.json'];
for (const directory of ['packages', 'apps'])
  for (const entry of await readdir(resolve(root, directory))) manifests.push(`${directory}/${entry}/package.json`);
for (const file of manifests) {
  const path = resolve(root, file),
    manifest = JSON.parse(await readFile(path, 'utf8'));
  manifest.version = version;
  for (const field of ['dependencies', 'devDependencies', 'peerDependencies'])
    for (const name of Object.keys(manifest[field] ?? {}))
      if (name.startsWith('@logiparity/')) manifest[field][name] = version;
  await writeFile(path, JSON.stringify(manifest, null, 2) + '\n');
}
await writeFile(
  resolve(root, 'packages/cli/src/version.ts'),
  `// Generated by release:bump.\nexport const version = '${version}';\n`,
);
const lockPath = resolve(root, 'package-lock.json'),
  lock = JSON.parse(await readFile(lockPath, 'utf8'));
lock.version = version;
for (const [path, entry] of Object.entries(lock.packages)) {
  if (path === '' || manifests.includes(path + '/package.json')) entry.version = version;
  for (const field of ['dependencies', 'devDependencies', 'peerDependencies'])
    for (const name of Object.keys(entry[field] ?? {}))
      if (name.startsWith('@logiparity/')) entry[field][name] = version;
}
await writeFile(lockPath, JSON.stringify(lock, null, 2) + '\n');
console.log(
  `Updated first-party versions to ${version}. Run npm install --package-lock-only, checks, then review the diff. Nothing tagged or published.`,
);

// Human release history is edited during review, never by a global replacement.
for (const file of [
  'README.md',
  'templates/github-actions.yml',
  'templates/github-actions-container.yml',
  'templates/gitlab-ci.yml',
]) {
  const path = resolve(root, file),
    text = await readFile(path, 'utf8');
  const next = text
    .split('\n')
    .map((line) => {
      if (/^\s*LOGIPARITY_VERSION:/.test(line))
        return line.replace(/(['"]?)(\d+\.\d+\.\d+)\1/, (token, _quote, found) =>
          found === previous ? `'${version}'` : token,
        );
      if (!/\b(?:npm\s+(?:install|i)|npx)\b/.test(line)) return line;
      return line
        .replace(/\blogiparity@(\d+\.\d+\.\d+)/g, (token, found) =>
          found === previous ? `logiparity@${version}` : token,
        )
        .replace(/\blogiparity-(\d+\.\d+\.\d+)\.tgz/g, (token, found) =>
          found === previous ? `logiparity-${version}.tgz` : token,
        );
    })
    .join('\n');
  await writeFile(path, next);
}
